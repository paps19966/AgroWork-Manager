package gr.agro;

public class EmpFarm {

    private String documentId;
    private String employeeDocumentId;
    private String farmDocumentId;


    public String getDocumentId() {
        return documentId;
    }

    public void setDocumentId(String documentId) {
        this.documentId = documentId;
    }

    public String getEmployeeDocumentId() {
        return employeeDocumentId;
    }

    public void setEmployeeDocumentId(String employeeDocumentId) {
        this.employeeDocumentId = employeeDocumentId;
    }

    public String getFarmDocumentId() {
        return farmDocumentId;
    }

    public void setFarmDocumentId(String farmDocumentId) {
        this.farmDocumentId = farmDocumentId;
    }
}
